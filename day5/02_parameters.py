# This is a simple example of using parameters in Python functions.
def greet(name):
    print(f"Hello {name}")


greet("Tridib")
# Output: Hello Tridib
greet("Rahul")
# Output: Hello Rahul


# This is a simple example of using multiple parameters in Python functions.
def introduce(name, company):
    print(f"{name} works at {company}")


introduce("Tridib", "ABC")
# Output: Tridib works at ABC
