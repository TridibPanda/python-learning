# List
fruits = ["Apple", "Banana", "Mango"]
print(fruits)
# Output: ['Apple', 'Banana', 'Mango']
print(fruits[0])  # Access list item
# Output: Apple
print(fruits[-1])  # Negative index
# Output: Mango
print(len(fruits))  # List length
# Output: 3
print(fruits.index("Mango"))  # Item index
# Output: 2
print(fruits.count("Mango"))  # Counts total occurrences.
# Output: 1

# Loop list
for fruit in fruits:
    print(fruit)
# Output:
# Apple
# Banana
# Mango
