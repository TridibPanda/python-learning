# Old style string formatting
name = "Tridib"
print("Hello " + name)
# Output: Hello Tridib

# Modern style string formatting using f-strings
name = "Tridib"
print(f"Hello {name}")
# Output: Hello Tridib

name = "Tridib"
company = "PwC"
age = 25
print(f"My name is {name}. I work at {company}. I am {age} years old.")
# Output: My name is Tridib. I work at PwC. I am 25 years old.
