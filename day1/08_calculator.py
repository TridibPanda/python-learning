# Simple Calculator
first_number = int(input("Enter first number: "))
second_number = int(input("Enter second number: "))

print(f"Addition: {first_number + second_number}")
# Output: Addition: <sum_of_first_and_second_number>
print(f"Subtraction: {first_number - second_number}")
# Output: Subtraction: <difference_of_first_and_second_number>
print(f"Multiplication: {first_number * second_number}")
# Output: Multiplication: <product_of_first_and_second_number>
print(f"Division: {first_number / second_number}")
# Output: Division: <quotient_of_first_and_second_number>
